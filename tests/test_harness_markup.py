"""Tests for harness-injected markup stripping and title selection (ADR-0015)."""
from __future__ import annotations

from types import SimpleNamespace

from ai_memory.core.dreaming import _render_transcript
from ai_memory.harness_markup import (
    TITLE_MAX_CHARS,
    is_scheduled_task_run,
    strip_injected,
    title_candidate,
)

REMINDER = (
    "<system-reminder>\nContents of CLAUDE.md:\n# Global\n- be direct\n"
    "<not-a-real-tag>\n</system-reminder>"
)


# --- strip_injected ---------------------------------------------------------


def test_strip_leading_reminder() -> None:
    assert strip_injected(f"{REMINDER}\n\nlet's fix ai-memory") == "let's fix ai-memory"


def test_strip_multiple_reminders_and_caveat() -> None:
    text = (
        f"{REMINDER}{REMINDER}\n<local-command-caveat>Caveat: generated by local "
        "commands.</local-command-caveat>\nhello\n\n\n\nworld"
    )
    assert strip_injected(text) == "hello\n\nworld"


def test_strip_reminder_with_attributes() -> None:
    assert strip_injected('<system-reminder id="x">noise</system-reminder>ok') == "ok"


def test_strip_reminder_only_turn_becomes_empty() -> None:
    assert strip_injected(REMINDER) == ""


def test_strip_leaves_unpaired_mention_alone() -> None:
    text = "why is every title <system-reminder> now?"
    assert strip_injected(text) == text


def test_strip_no_markup_is_identity() -> None:
    text = "  plain text, untouched  \n\n\n\n spacing too "
    assert strip_injected(text) == text


def test_strip_keeps_pasted_content() -> None:
    text = '<pasted_content id="a1">user data</pasted_content>\nsummarise this'
    assert strip_injected(text) == text


# --- title_candidate --------------------------------------------------------


def test_title_skips_reminder() -> None:
    assert title_candidate(f"{REMINDER}\nlet's fix ai-memory\nmore") == "let's fix ai-memory"


def test_title_slash_command() -> None:
    text = (
        "<command-message>simplify is running…</command-message>\n"
        "<command-name>/simplify</command-name>\n<command-args>the  diff</command-args>"
    )
    assert title_candidate(text) == "/simplify the diff"


def test_title_slash_command_without_slash_or_args() -> None:
    assert title_candidate("<command-name>init</command-name>") == "/init"


def test_title_prefers_own_words_over_pasted_content() -> None:
    text = '<pasted_content id="a">long log line\nmore</pasted_content>\nwhat broke here?'
    assert title_candidate(text) == "what broke here?"


def test_title_none_for_notification_only() -> None:
    text = "<task-notification><task-id>t1</task-id><status>done</status></task-notification>"
    assert title_candidate(text) is None


def test_title_none_for_reminder_only() -> None:
    assert title_candidate(REMINDER) is None


def test_title_strips_unknown_wrapper_tags() -> None:
    assert title_candidate("<scheduled-task>run the brief</scheduled-task>") == "run the brief"


def test_title_truncated() -> None:
    assert title_candidate("x" * 500) == "x" * TITLE_MAX_CHARS


# --- dream render ------------------------------------------------------------


class _StubRaw:
    def __init__(self, payloads: dict[str, dict]) -> None:
        self._payloads = payloads

    def read_turn(self, raw_file: str, byte_offset: int, byte_length: int) -> dict:
        return self._payloads[raw_file]


def test_render_strips_user_reminders_but_not_assistant_text() -> None:
    raw = _StubRaw({
        "u": {"role": "user", "text": f"{REMINDER}\nhi"},
        "a": {"role": "assistant", "text": f"quoting: {REMINDER}"},
    })
    turns = [
        SimpleNamespace(raw_file="u", byte_offset=0, byte_length=0),
        SimpleNamespace(raw_file="a", byte_offset=0, byte_length=0),
    ]
    rendered = _render_transcript(raw, turns)
    assert rendered.splitlines()[:4] == [
        "<conversation_transcript>", "<turn n=1 role=user>", "hi", "</turn>",
    ]
    assert rendered.count("<system-reminder>") == 1  # the assistant's quote survives


# --- is_scheduled_task_run ----------------------------------------------------


def test_scheduled_task_tag_matches() -> None:
    assert is_scheduled_task_run('<scheduled-task name="x" file="y">\nThis is an automated run')


def test_scheduled_task_plain_prompt_matches() -> None:
    assert is_scheduled_task_run("This is an automated run of a scheduled task. The user is away.")


def test_scheduled_task_after_leading_reminder_matches() -> None:
    text = "<system-reminder>\nscratch workspace\n</system-reminder>\n\n<scheduled-task name=\"x\">"
    assert is_scheduled_task_run(text)


def test_scheduled_task_mentioned_mid_turn_does_not_match() -> None:
    assert not is_scheduled_task_run("why did <scheduled-task name=\"x\"> fail last night?")
